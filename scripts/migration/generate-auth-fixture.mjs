#!/usr/bin/env node
/**
 * Generates a JWT fixture using the real Node jose library.
 * This fixture is consumed by Go tests to prove actual Node → Go JWT interoperability.
 *
 * IMPORTANT: Uses a hardcoded test secret — NEVER reads production JWT_SECRET.
 *
 * Usage:
 *   node scripts/migration/generate-auth-fixture.mjs
 *
 * Output:
 *   backend/testdata/auth/node-jose-token.json
 */

import { SignJWT } from 'jose';
import { writeFileSync, mkdirSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = resolve(__dirname, '../..');
const OUT_PATH = resolve(ROOT, 'backend/testdata/auth/node-jose-token.json');

// Test-only secret — 32+ bytes, never used in production
const TEST_SECRET = 'phase2-test-secret-only-not-for-production-xcloud';
const secretKey = new TextEncoder().encode(TEST_SECRET);

const now = Math.floor(Date.now() / 1000);
const ONE_YEAR = 365 * 24 * 60 * 60;

// ── Fixture 1: Valid token ──────────────────────────────────────────────────

const validToken = await new SignJWT({
  username: 'phase2_test_user',
  role: 'admin',
  sv: 3,
})
  .setProtectedHeader({ alg: 'HS256', typ: 'JWT' })
  .setIssuedAt(now)
  .setExpirationTime(now + ONE_YEAR)
  .sign(secretKey);

// ── Fixture 2: Expired token ────────────────────────────────────────────────

const expiredToken = await new SignJWT({
  username: 'phase2_test_user',
  role: 'admin',
  sv: 3,
})
  .setProtectedHeader({ alg: 'HS256', typ: 'JWT' })
  .setIssuedAt(now - 7200)
  .setExpirationTime(now - 3600) // expired 1 hour ago
  .sign(secretKey);

// ── Fixture 3: Wrong algorithm (RS256 signed — should be rejected) ──────────
// We don't generate RS256 here because Go only accepts HS256.
// Instead we craft an alg=none token to test algorithm rejection.

const algNoneHeader = Buffer.from(JSON.stringify({ alg: 'none', typ: 'JWT' })).toString('base64url');
const algNonePayload = Buffer.from(JSON.stringify({
  username: 'phase2_test_user',
  role: 'admin',
  sv: 3,
  exp: now + ONE_YEAR,
})).toString('base64url');
const algNoneToken = `${algNoneHeader}.${algNonePayload}.`;

// ── Write output ────────────────────────────────────────────────────────────

mkdirSync(dirname(OUT_PATH), { recursive: true });

const fixture = {
  description: 'TEST ONLY — generated by Node jose library for Go cross-language verification',
  generatedAt: new Date().toISOString(),
  generator: 'scripts/migration/generate-auth-fixture.mjs',
  library: 'jose ^6.2.2',
  algorithm: 'HS256',
  testSecret: TEST_SECRET,
  fixtures: {
    valid: {
      description: 'Valid HS256 token with all required claims',
      token: validToken,
      claims: {
        username: 'phase2_test_user',
        role: 'admin',
        sv: 3,
      },
    },
    expired: {
      description: 'Expired token — should be rejected by Go verifier',
      token: expiredToken,
      claims: {
        username: 'phase2_test_user',
        role: 'admin',
        sv: 3,
      },
    },
    algNone: {
      description: 'alg=none token — should be rejected by Go verifier',
      token: algNoneToken,
      claims: {
        username: 'phase2_test_user',
        role: 'admin',
        sv: 3,
      },
    },
  },
};

writeFileSync(OUT_PATH, JSON.stringify(fixture, null, 2) + '\n');
console.log(`✅ Fixture written to ${OUT_PATH}`);
console.log(`   Valid token:   ${validToken.slice(0, 40)}...`);
console.log(`   Expired token: ${expiredToken.slice(0, 40)}...`);
console.log(`   alg=none:      ${algNoneToken.slice(0, 40)}...`);
